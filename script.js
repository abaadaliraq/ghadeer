const supportedLanguages = ["ar", "en", "fr"];
let currentLanguage = "ar";

function getTranslation(path, language = currentLanguage) {
  return path.split(".").reduce((value, key) => value?.[key], translations[language]) ?? "";
}

function getLocalized(value) {
  if (value && typeof value === "object") {
    return value[currentLanguage] ?? value.ar ?? "";
  }

  return value ?? "";
}

function toCounterNumber(value) {
  return String(value).padStart(2, "0");
}

function applyStaticTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = getTranslation(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = getTranslation(element.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(";").forEach((pair) => {
      const [attribute, key] = pair.split(":");
      const value = getTranslation(key);

      if (attribute && value) {
        element.setAttribute(attribute, value);
      }
    });
  });

  document.title = getTranslation("meta.title");
}

function updateLanguageControls() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function createArtworkBlock(artwork) {
  const article = document.createElement("article");
  article.className = "artwork-block";

  const title = getLocalized(artwork.title);
  const category = getLocalized(artwork.category);
  const description = getLocalized(artwork.description);
  const detailsTitle = getTranslation("artworks.detailsTitle");

  const detailsMarkup = artwork.details
    .map(
      (src, index) => `
        <figure class="detail-slide" data-detail-slide>
          <img src="${src}" alt="${detailsTitle} ${toCounterNumber(index + 1)} — ${title}" loading="lazy" />
        </figure>`
    )
    .join("");

  const specsMarkup = artwork.material
    ? `<div class="artwork-specs reveal-item artwork-reveal-3">
        <p>${getTranslation("artworks.materialLabel")}: ${getLocalized(artwork.material)}</p>
        <p>${getTranslation("artworks.sizeLabel")}: ${artwork.size}</p>
      </div>`
    : "";

  article.innerHTML = `
    <figure class="artwork-main-image reveal-item artwork-reveal-1">
      <img src="${artwork.mainImage}" alt="${title}" loading="lazy" />
    </figure>

    <div class="artwork-content">
      <div class="artwork-number reveal-item artwork-reveal-2">
        <span>${toCounterNumber(artwork.id)}</span>
        <span>${title}</span>
      </div>

      <div class="artwork-title-group reveal-item artwork-reveal-2">
        <h3>${title}</h3>
        <p class="artwork-subtitle">${category}</p>
      </div>

      <p class="artwork-description reveal-item artwork-reveal-3">${description}</p>
      ${specsMarkup}
    </div>

    <section class="detail-gallery reveal-item artwork-reveal-4" aria-label="${detailsTitle} — ${title}">
      <div class="detail-gallery-header">
        <p class="detail-gallery-title">${detailsTitle}</p>
        <p class="detail-counter" data-detail-counter>01 / ${toCounterNumber(artwork.details.length)}</p>
      </div>
      <div class="detail-track" data-detail-track>${detailsMarkup}</div>
    </section>
  `;

  return article;
}

function renderArtworks() {
  const container = document.querySelector("#artworks-list");

  if (!container) {
    return;
  }

  container.innerHTML = "";
  artworks.forEach((artwork) => container.appendChild(createArtworkBlock(artwork)));
}

function updateDetailCounter(gallery) {
  const track = gallery.querySelector("[data-detail-track]");
  const counter = gallery.querySelector("[data-detail-counter]");
  const slides = Array.from(gallery.querySelectorAll("[data-detail-slide]:not(.is-hidden)"));

  if (!track || !counter) {
    return;
  }

  if (slides.length === 0) {
    gallery.classList.add("is-empty");
    return;
  }

  gallery.classList.remove("is-empty");

  const trackBox = track.getBoundingClientRect();
  const trackCenter = trackBox.left + trackBox.width / 2;
  let activeIndex = 0;
  let closestDistance = Number.POSITIVE_INFINITY;

  slides.forEach((slide, index) => {
    const slideBox = slide.getBoundingClientRect();
    const slideCenter = slideBox.left + slideBox.width / 2;
    const distance = Math.abs(trackCenter - slideCenter);

    if (distance < closestDistance) {
      closestDistance = distance;
      activeIndex = index;
    }
  });

  counter.textContent = `${toCounterNumber(activeIndex + 1)} / ${toCounterNumber(slides.length)}`;
}

function setupDetailGalleries() {
  document.querySelectorAll(".detail-gallery").forEach((gallery) => {
    const track = gallery.querySelector("[data-detail-track]");
    const slides = Array.from(gallery.querySelectorAll("[data-detail-slide]"));

    if (!track) {
      return;
    }

    slides.forEach((slide) => {
      const img = slide.querySelector("img");

      img.addEventListener("load", () => updateDetailCounter(gallery));
      img.addEventListener("error", () => {
        slide.classList.add("is-hidden");
        updateDetailCounter(gallery);
      });
    });

    let isDragging = false;
    let startX = 0;
    let startScrollLeft = 0;

    track.addEventListener("pointerdown", (event) => {
      if (event.pointerType === "touch") {
        return;
      }

      isDragging = true;
      startX = event.clientX;
      startScrollLeft = track.scrollLeft;
      track.classList.add("is-dragging");
      track.setPointerCapture(event.pointerId);
    });

    track.addEventListener("pointermove", (event) => {
      if (!isDragging) {
        return;
      }

      event.preventDefault();
      track.scrollLeft = startScrollLeft - (event.clientX - startX);
    });

    ["pointerup", "pointercancel", "pointerleave"].forEach((eventName) => {
      track.addEventListener(eventName, () => {
        isDragging = false;
        track.classList.remove("is-dragging");
      });
    });

    track.addEventListener("scroll", () => updateDetailCounter(gallery), { passive: true });
    updateDetailCounter(gallery);
  });
}

function revealOnScroll(selector) {
  const elements = document.querySelectorAll(selector);

  if (!("IntersectionObserver" in window)) {
    elements.forEach((element) => element.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { rootMargin: "0px 0px -15% 0px", threshold: 0.01 }
  );

  elements.forEach((element) => observer.observe(element));
}

function setupContactLinks() {
  document.querySelectorAll("[data-contact-link]").forEach((link) => {
    const key = link.dataset.contactLink;
    const value = artistContact[key] || "#";

    link.href = value;

    if (key === "website") {
      const websiteText = link.querySelector("[data-contact-website-text]");

      if (websiteText) {
        websiteText.textContent = value.replace(/^https?:\/\//, "").replace(/\/$/, "");
      }
    }

    link.addEventListener("click", (event) => {
      if (value === "#") {
        event.preventDefault();
      }
    });
  });
}

function setupOptionalImages() {
  document.querySelectorAll("[data-optional-image]").forEach((figure) => {
    const image = figure.querySelector("img");

    if (!image) {
      return;
    }

    const showImage = () => {
      figure.classList.add("is-loaded");
    };

    const removeImage = () => {
      figure.remove();
    };

    image.addEventListener("load", showImage);
    image.addEventListener("error", removeImage);

    if (image.complete) {
      if (image.naturalWidth > 0) {
        showImage();
      } else {
        removeImage();
      }
    }
  });
}

function applyLanguage(language, options = {}) {
  const nextLanguage = supportedLanguages.includes(language) ? language : "ar";
  const scrollY = window.scrollY;

  currentLanguage = nextLanguage;
  document.documentElement.lang = nextLanguage;
  document.documentElement.dir = nextLanguage === "ar" ? "rtl" : "ltr";
  document.body.dataset.lang = nextLanguage;

  applyStaticTranslations();
  renderArtworks();
  setupDetailGalleries();
  updateLanguageControls();
  revealOnScroll(".artwork-block");

  document.querySelectorAll(".artworks-section.is-visible .artwork-block").forEach((block) => {
    block.classList.add("is-visible");
  });

  if (!options.skipStorage) {
    localStorage.setItem("brochureLanguage", nextLanguage);
  }

  window.scrollTo(0, scrollY);
  requestAnimationFrame(() => window.scrollTo(0, scrollY));
}

function setupLanguageSwitcher() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.lang);
    });
  });
}

window.addEventListener("DOMContentLoaded", () => {
  requestAnimationFrame(() => {
    document.documentElement.classList.add("is-ready");
  });

  const savedLanguage = localStorage.getItem("brochureLanguage") || "ar";

  setupLanguageSwitcher();
  applyLanguage(savedLanguage, { skipStorage: !localStorage.getItem("brochureLanguage") });
  setupOptionalImages();
  setupContactLinks();
  revealOnScroll(".artist-section, .artworks-section, .artwork-block, .house-section, .contact-section");
});


