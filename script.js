const supportedLanguages = ["ar", "en", "fr"];
let currentLanguage = "ar";

function getTranslation(path, language = currentLanguage) {
  return path.split(".").reduce((value, key) => value?.[key], translations[language]) ?? "";
}

function getLocalized(value) {
  if (value && typeof value === "object") {
    return value[currentLanguage] ?? value.ar ?? "";
  }

  return value ?? "";
}

function toCounterNumber(value) {
  return String(value).padStart(2, "0");
}

function applyStaticTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = getTranslation(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = getTranslation(element.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(";").forEach((pair) => {
      const [attribute, key] = pair.split(":");
      const value = getTranslation(key);

      if (attribute && value) {
        element.setAttribute(attribute, value);
      }
    });
  });

  document.title = getTranslation("meta.title");
}

function updateLanguageControls() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}


function artworkSpecs(artwork) {
  if (artwork.dimensions) return artwork.dimensions.map((value, index) =>
    '<p><span>' + getTranslation('artworks.' + ['width','height','depth'][index]) + '</span><bdi>' + value + ' ' + getTranslation('artworks.cm') + '</bdi></p>'
  ).join('');
  return artwork.measurement ? '<p><span>' + getTranslation('artworks.measure') + '</span><bdi>' + artwork.measurement + ' ' + getTranslation('artworks.mm') + '</bdi></p>' : '';
}

function createArtworkBlock(artwork) {
  const article = document.createElement('article');
  article.className = 'artwork-block';
  article.dataset.artworkId = artwork.id;
  const imageMarkup = index => '<figure class="artwork-main-image"><img src="' + artwork.images[index] + '" alt="' + getLocalized(artwork.imageAlt) + ' — ' + (index+1) + '" loading="lazy" decoding="async" /><figcaption class="artwork-image-unavailable" hidden>' + getTranslation('artworks.missing') + '</figcaption></figure>';
  const specs = artworkSpecs(artwork);
  article.innerHTML = imageMarkup(0) +
    '<div class="artwork-content"><span class="artwork-number" dir="ltr">' + toCounterNumber(artwork.id) + '</span><h3>' + getLocalized(artwork.title) + '</h3>' +
    '<div class="artwork-full-description">' + getLocalized(artwork.description).map(paragraph=>'<p>'+paragraph+'</p>').join('') + '</div>' +
    (specs ? '<div class="artwork-specs">'+specs+'</div>' : '') + '</div>' + imageMarkup(1);
  article.querySelectorAll('img').forEach(img=> {
    const showMissing = () => {img.hidden = true; img.nextElementSibling.hidden = false;};
    img.addEventListener('error', showMissing, {once:true});
    if(img.complete && !img.naturalWidth) showMissing();
  });
  return article;
}

function renderArtworks() {
  const container = document.querySelector('#artworks-list');
  if (container) container.replaceChildren(...artworks.map(createArtworkBlock));
}

function revealOnScroll(selector) {
  const elements = document.querySelectorAll(selector);

  if (!("IntersectionObserver" in window)) {
    elements.forEach((element) => element.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { rootMargin: "0px 0px -15% 0px", threshold: 0.01 }
  );

  elements.forEach((element) => observer.observe(element));
}

function setupContactLinks() {
  document.querySelectorAll("[data-contact-link]").forEach((link) => {
    const key = link.dataset.contactLink;
    const value = artistContact[key] || "#";

    link.href = value;

    if (key === "website") {
      const websiteText = link.querySelector("[data-contact-website-text]");

      if (websiteText) {
        websiteText.textContent = value.replace(/^https?:\/\//, "").replace(/\/$/, "");
      }
    }

    link.addEventListener("click", (event) => {
      if (value === "#") {
        event.preventDefault();
      }
    });
  });
}

function setupOptionalImages() {
  document.querySelectorAll("[data-optional-image]").forEach((figure) => {
    const image = figure.querySelector("img");

    if (!image) {
      return;
    }

    const showImage = () => {
      figure.classList.add("is-loaded");
    };

    const removeImage = () => {
      figure.remove();
    };

    image.addEventListener("load", showImage);
    image.addEventListener("error", removeImage);

    if (image.complete) {
      if (image.naturalWidth > 0) {
        showImage();
      } else {
        removeImage();
      }
    }
  });
}

function applyLanguage(language, options = {}) {
  const nextLanguage = supportedLanguages.includes(language) ? language : "ar";
  const scrollY = window.scrollY;

  currentLanguage = nextLanguage;
  document.documentElement.lang = nextLanguage;
  document.documentElement.dir = nextLanguage === "ar" ? "rtl" : "ltr";
  document.body.dataset.lang = nextLanguage;

  applyStaticTranslations();
  renderArtworks();
  updateLanguageControls();
  revealOnScroll(".artwork-block");

  document.querySelectorAll(".artworks-section.is-visible .artwork-block").forEach((block) => {
    block.classList.add("is-visible");
  });

  if (!options.skipStorage) {
    localStorage.setItem("brochureLanguage", nextLanguage);
  }

  window.scrollTo(0, scrollY);
  requestAnimationFrame(() => window.scrollTo(0, scrollY));
}

function setupLanguageSwitcher() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.lang);
    });
  });
}

window.addEventListener("DOMContentLoaded", () => {
  requestAnimationFrame(() => {
    document.documentElement.classList.add("is-ready");
  });

  const savedLanguage = localStorage.getItem("brochureLanguage") || "ar";

  setupLanguageSwitcher();
  applyLanguage(savedLanguage, { skipStorage: !localStorage.getItem("brochureLanguage") });
  setupOptionalImages();
  setupContactLinks();
  revealOnScroll(".artist-section, .artworks-section, .artwork-block, .house-section, .contact-section");
});


